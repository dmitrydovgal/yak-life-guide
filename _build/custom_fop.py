def money(x):
    s = f'{x:,.2f}'.replace(',', ' ').replace('.', ',')
    return s[:-3] if s.endswith(',00') else s


def human(d):
    m = ['січня', 'лютого', 'березня', 'квітня', 'травня', 'червня', 'липня', 'серпня', 'вересня', 'жовтня', 'листопада', 'грудня']
    y, mm, dd = d.split('-')
    return f'{int(dd)} {m[int(mm) - 1]} {y}'


