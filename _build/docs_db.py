def human_date(d):
    y, m, dd = d.split('-')
    return f'{int(dd)} {_MONTHS[int(m) - 1]} {y}'


def host(u):
    return re.sub(r'^https://(?:www\.)?([^/]+).*$', r'\1', u)


def services_of(doc_id):
    return sorted(s for s, l in LINKS.items() if any(x['doc'] == doc_id for x in l['docs']))


def check():
    """Падає під час збірки, якщо запис порушує правила."""
    cats = {c for c, _ in CATS}
    for i, d in DOCS.items():
        assert re.fullmatch(r'[a-z0-9-]+', i), i
        for k in ('title', 'plain', 'purpose', 'cat', 'kind', 'src', 'fill', 'checked', 'status'):
            assert d.get(k), f'{i}: немає {k}'
        assert d['status'] == 'verified', i
        assert d['cat'] in cats and d['kind'] in KINDS, i
        assert re.fullmatch(r'\d{4}-\d\d-\d\d', d['checked']), i
        urls = [d['src']['url']] + ([d['file']['url']] if d.get('file') else [])
        for u in urls:
            assert u.startswith('https://') and host(u).endswith(OFFICIAL_HOSTS), f'{i}: неофіційне джерело {u}'
        if d['kind'] == 'blank':
            assert d.get('file') and d['file'].get('fmt') and '/laws/file/' in d['file']['url'], i + ': бланк без файлу'
        else:
            assert not d.get('file') and d.get('basis'), i + ': пояснення без підстави'
        assert services_of(i), i + ': документ без послуг'
    for s, l in LINKS.items():
        assert re.fullmatch(r'\d{5}', s), s
        main = [x for x in l['docs'] if not x.get('also')]
        assert main, s
        for x in l['docs']: assert x['doc'] in DOCS, f'{s}: {x["doc"]}'
        if len(main) > 1: assert all(x.get('who') for x in main), s + ': кілька бланків — потрібно «для кого»'
        kinds = {DOCS[x['doc']]['kind'] for x in main}
        assert len(kinds) == 1, s + ': змішано бланк і «бланк не потрібен»'
