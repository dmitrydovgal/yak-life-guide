_MONTHS = ['січня', 'лютого', 'березня', 'квітня', 'травня', 'червня', 'липня', 'серпня', 'вересня', 'жовтня', 'листопада', 'грудня']


def human_date(d):
    y, m, dd = d.split('-')
    return f'{int(dd)} {_MONTHS[int(m) - 1]} {y}'


def host(u):
    return re.sub(r'^https://(?:www\.)?([^/]+).*$', r'\1', u)


def check():
    """Падає під час збірки, якщо запис порушує правила вище."""
    for sid, f in FORMS.items():
        assert re.fullmatch(r'\d{5}', sid), sid
        assert f.get('blanks') or f.get('examples') or f.get('noBlank'), sid + ': порожній запис'
        assert not (f.get('noBlank') and f.get('blanks')), sid + ': і бланк, і «бланк не потрібен»'
        if f.get('noBlank'): assert f.get('basis'), sid + ': немає підстави для «бланк не потрібен»'
        many = len(f.get('blanks', [])) > 1
        for x in f.get('blanks', []) + f.get('examples', []):
            for k in ('title', 'url', 'src', 'srcUrl', 'checked'): assert x.get(k), f'{sid}: немає {k}'
            for u in (x['url'], x['srcUrl']):
                assert u.startswith('https://') and host(u).endswith(OFFICIAL_HOSTS), f'{sid}: неофіційне джерело {u}'
            assert re.fullmatch(r'\d{4}-\d\d-\d\d', x['checked']), sid
            if many: assert x.get('who'), sid + ': кілька бланків — для кожного потрібно «для кого»'
            if x.get('act'): assert x.get('where'), sid + ': посилання на акт без підказки, де в ньому форма'
            else: assert x.get('fmt'), sid + ': для файлу потрібен формат'
        for x in f.get('examples', []): assert 'official' in x, sid + ': приклад без позначки official'


def for_service(sid):
    """Дані для journey-data та статичної сторінки; None — блоку немає."""
    f = FORMS.get(sid)
    if not f: return None
    out = {}
    for k in ('blanks', 'examples'):
        if f.get(k): out[k] = [dict(x, checkedText=human_date(x['checked']), host=host(x['url'])) for x in f[k]]
    for k in ('noBlank', 'note', 'tips'):
        if f.get(k): out[k] = f[k]
    return out
