def clean(s):
    return re.sub(r'\s+', ' ', (s or '').replace('\r', ' ').replace('\n', ' ')).strip()

def cut(s, n):
    s = clean(s)
    if len(s) <= n: return s
    c = s[:n]
    k = max(c.rfind('. '), c.rfind('; '), c.rfind(', '), c.rfind(' '))
    return (c[:k] if k > n * .5 else c).rstrip(' ,;.') + '…'

def variants(s):
    # "Звичайне надання: Безоплатне надання; Прискорене: 928 UAH" -> unique short list
    s = clean(s)
    parts = [p.strip() for p in s.split(';') if p.strip()]
    out = []
    for p in parts:
        if p not in out: out.append(p)
    if len(out) == 1 and out[0].startswith('Звичайне надання: '):
        out[0] = out[0][len('Звичайне надання: '):]
    return cut('; '.join(out[:3]), 220)

def ways(lst):
    s = set()
    for w in lst or []:
        if ':' in w:
            for p in re.split(r'[;,]', w.split(':', 1)[1]):
                p = p.strip()
                if p: s.add(p)
    order = ['Особисто', 'Письмово', 'Усно', 'Електронно', 'Поштою']
    return sorted(s, key=lambda x: order.index(x) if x in order else 99)

